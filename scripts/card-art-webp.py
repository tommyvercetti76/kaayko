#!/usr/bin/env python3
"""
Encode the card art for the web: src/assets/cards/art/<slug>.png -> <slug>.webp,
and write src/js/cards/art.js, the URL of each with a content hash.

WHY THIS EXISTS
---------------
The six PNGs are the print masters (802 x 1200, full colour) and were also what
the web card downloaded: 245-714 KB each, 2.7 MB for the set. As WebP at q88
they are 30-110 KB, 358 KB for the set, and look the same at the size the
card shows them. The PNGs stay: the print sheet and the admin preview read
them, and they are the source this is made from.

The URL carries a hash of the WebP's bytes, so firebase.json can cache the
WebP for a year (immutable): changed art is a different URL, and an unchanged
one is never asked for twice.

RUN THIS WHENEVER A PNG IN src/assets/cards/art CHANGES:
    python3 scripts/card-art-webp.py
It also rewrites the first card's <link rel="preload"> in src/index.html.
Needs Pillow (python3 -m pip install Pillow).
"""
import hashlib
import json
import pathlib
import re

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
ART = ROOT / "src" / "assets" / "cards" / "art"
OUT_JS = ROOT / "src" / "js" / "cards" / "art.js"
INDEX = ROOT / "src" / "index.html"
QUALITY = 88
FIRST = "paddlingout"   # the first card in the series; its art is preloaded

urls = {}
for png in sorted(ART.glob("*.png")):
    webp = png.with_suffix(".webp")
    Image.open(png).save(webp, "WEBP", quality=QUALITY, method=6)
    digest = hashlib.sha256(webp.read_bytes()).hexdigest()[:10]
    urls[png.stem] = f"/assets/cards/art/{png.stem}.webp?v={digest}"
    print(f"{png.stem:12} {png.stat().st_size // 1024:4} KB png -> {webp.stat().st_size // 1024:4} KB webp")

OUT_JS.write_text(
    "/**\n"
    " * cards/art.js — where the web card's art lives. GENERATED by\n"
    " * scripts/card-art-webp.py from src/assets/cards/art/*.png; do not edit by hand.\n"
    " * WebP for the screen (the PNGs are the print masters), with a content hash so\n"
    " * the files can be cached for a year.\n"
    " */\n"
    f"const URLS = Object.freeze({json.dumps(urls, indent=2)});\n\n"
    "/** The art for a card on the web: the WebP, or the PNG for a slug with none. */\n"
    "export const artUrl = (c) => URLS[c.art || c.slug] || `/assets/cards/art/${c.art || c.slug}.png`;\n"
)

html = INDEX.read_text()
tag = f'<link rel="preload" as="image" type="image/webp" fetchpriority="high" href="{urls[FIRST]}">'
pattern = re.compile(r'<link rel="preload" as="image" type="image/webp" fetchpriority="high" href="[^"]*">')
if pattern.search(html):
    html = pattern.sub(tag, html, count=1)
else:
    raise SystemExit("index.html has no first-card preload tag to update; add it once by hand next to the fonts")
INDEX.write_text(html)
print(f"wrote {OUT_JS.relative_to(ROOT)} and the preload for {FIRST}")
