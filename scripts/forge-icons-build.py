#!/usr/bin/env python3
"""Forge condition-icon renders -> one small JS file of traced, single-fill SVG icons.

Run with the Frameworks python (Pillow, numpy, scipy, vtracer):
  /Library/Frameworks/Python.framework/Versions/3.13/bin/python3 scripts/forge-icons-build.py [--preview out.png]

Each icon is a Forge render Rohan picked from a contact sheet (PICKS below: name -> render
path, and the luminance cut that keys its ink; grey renders need a higher cut than black
ones). The trace is scripts/scouts-rules-svg.py's, unchanged, at 256 units instead of 1024:
these are drawn at about 20px, and a 1024-unit path is 5 KB of detail nobody can see.
Output: src/js/kaayko-icons-forge.js, which adds the icons to window.KaaykoIcons under
their own names (fill: currentColor, so they take the page's gold like every other icon).
"""
import importlib.util, re, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
R1 = Path.home() / 'Desktop/Kaayko_Derived/forge-conditions-icons-2026-11-16-bold-seed600'
R2 = Path.home() / 'Desktop/Kaayko_Derived/forge-conditions-icons-2026-11-16-round2-seed700'
R3 = Path.home() / 'Desktop/Kaayko_Derived/forge-conditions-icons-2026-11-16-round3-seed800'

# name -> (render, luminance cut). Edit when Rohan re-grades; never point at an unpicked render.
PICKS = {
    'fx-thermometer': (R3 / 'thermometer/seed03.png', 130),
    'fx-wind':        (R3 / 'wind/seed01.png', 130),
    'fx-gusts':       (R2 / 'gusts/seed03.png', 130),
    'fx-flow':        (R3 / 'flow/seed01.png', 130),
    'fx-compass':     (R1 / 'compass/seed03.png', 130),
    'fx-water-temp':  (R3 / 'watertemp/seed03.png', 215),   # the puddle is drawn in grey
    'fx-rain':        (R3 / 'rain/seed02.png', 130),
    'fx-cloud':       (R3 / 'cloud/seed02.png', 130),
}

spec = importlib.util.spec_from_file_location('tracer', HERE / 'scouts-rules-svg.py')
tracer = importlib.util.module_from_spec(spec); spec.loader.exec_module(tracer)
tracer.OUT = 256

# The tracer's clean() was written for objects with a signature to drop: it keeps the big
# components and whatever sits inside their box. An icon's small parts are the icon (the
# raindrops under a cloud fell outside that box and the rain icon came out as a bare cloud),
# so here every component of at least 1% of the largest is kept.
def _keep_parts(ink):
    from scipy import ndimage
    import numpy as np
    lab, n = ndimage.label(ink)
    if n == 0:
        raise SystemExit('no ink')
    sizes = ndimage.sum(ink, lab, range(1, n + 1))
    keep = np.zeros(n + 1, bool); keep[1:] = sizes >= 0.01 * sizes.max()
    return keep[lab]
tracer.clean = _keep_parts

def trace(src, thresh):
    with tempfile.TemporaryDirectory() as td:
        dst = Path(td) / 'i.svg'
        tracer.main(str(src), str(dst), thresh=thresh, speckle=3)
        svg = dst.read_text()
    return ''.join(re.findall(r'<path\b[^>]*/>', svg))

def build(picks=PICKS):
    out = {}
    for name, (src, thresh) in picks.items():
        if not Path(src).exists():
            raise SystemExit(f'missing render for {name}: {src}')
        out[name] = trace(src, thresh)
    return out

def js(icons):
    rows = ',\n'.join(f"    '{k}': f('{v}')" for k, v in icons.items())
    return ("""/**
 * kaayko-icons-forge.js — condition icons drawn by Forge, traced to one filled path each.
 * GENERATED by scripts/forge-icons-build.py from the renders Rohan picked; do not hand-edit.
 * Adds to window.KaaykoIcons (load after kaayko-icons.js). fill: currentColor.
 */
(function () {
  'use strict';
  function f(inner) {
    return '<svg viewBox="0 0 256 256" width="1em" height="1em" fill="currentColor" fill-rule="evenodd" stroke="none" aria-hidden="true" focusable="false">' + inner + '</svg>';
  }
  var ICONS = {
""" + rows + """
  };
  var K = window.KaaykoIcons;
  if (!K || typeof K.get !== 'function') return;
  var get = K.get;
  K.get = function (name) { return Object.prototype.hasOwnProperty.call(ICONS, name) ? ICONS[name] : get.call(K, name); };
}());
""")

def preview(icons, dst):
    """The set as the page shows it: gold on black, at 22px and at 72px."""
    import io, subprocess
    from PIL import Image
    try:
        import cairosvg
    except ImportError:
        cairosvg = None
    names = list(icons)
    W = 40 + len(names) * 120
    sheet = Image.new('RGB', (W, 260), (8, 8, 8))
    for i, n in enumerate(names):
        svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" fill="#b5935a" fill-rule="evenodd">{icons[n]}</svg>'
        for size, y in ((72, 30), (22, 160)):
            if cairosvg:
                png = cairosvg.svg2png(bytestring=svg.encode(), output_width=size * 2, output_height=size * 2)
                im = Image.open(io.BytesIO(png)).convert('RGBA')
            else:
                return None
            sheet.paste(im, (40 + i * 120, y), im)
    sheet.save(dst); return dst

if __name__ == '__main__':
    icons = build()
    target = HERE.parent / 'src/js/kaayko-icons-forge.js'
    if '--no-write' not in sys.argv:
        target.write_text(js(icons))
        print(f'{target}: {target.stat().st_size} bytes, {len(icons)} icons')
    for n, v in icons.items(): print(f'  {n}: {len(v)} bytes')
    if '--preview' in sys.argv:
        p = preview(icons, sys.argv[sys.argv.index('--preview') + 1])
        print('preview:', p or 'skipped (cairosvg not installed)')
